-- =========================================================================
-- Migration 029: Грандфазер доступа к «Библиотеке промптов»
-- =========================================================================
-- Одноразово выдаёт бессрочный entitlement 'prompts' всем пользователям,
-- которые существовали ДО запуска платного доступа, чтобы они не потеряли
-- промпты. Новые (зарегистрированные после отсечки) платят как обычно.
--
-- Отсечка по created_at заморожена литералом, поэтому повторный запуск не
-- раздаёт доступ новым пользователям. ON CONFLICT DO NOTHING делает миграцию
-- идемпотентной. Применять в Supabase SQL Editor ПОСЛЕ 028.
-- =========================================================================

INSERT INTO public.entitlements (user_id, product, source, expires_at)
SELECT p.id, 'prompts', 'grandfather', NULL
FROM public.profiles p
WHERE p.is_approved = true
  AND p.created_at <= '2026-09-05 23:59:59+00'
ON CONFLICT (user_id, product) DO NOTHING;
