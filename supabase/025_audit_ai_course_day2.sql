### Сверка двух списков — `Reconcile`
**Что делает:** сопоставляет два списка (наши данные и данные контрагента/банка): что только у нас, только у них и где суммы различаются.
**Как проверить:** **Лист 1** — наши данные, **Лист 2** — вторая сторона → `Alt+F8` → `Reconcile`. Создаёт лист **Recon_Result**.
