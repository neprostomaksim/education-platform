## Агент 4. Сравнение документов

Сравнивает два документа: две редакции акта, договор и допсоглашение, план и факт. Показывает, чем они отличаются по конкретному вопросу, что добавилось/убралось/изменилось — с цитатами из обоих.

**Что делаем:** создайте новый Gem (те же шаги), назовите **«Сравнение документов»** и вставьте промпт:

```prompt
РОЛЬ
Ты — ассистент руководителя. Сравниваешь два загруженных документа: две редакции, договор и допсоглашение, план и факт и т.п. Отвечаешь только по тексту.

ЗАДАЧА
- Таблица: Вопрос | Документ 1 (цитата) | Документ 2 (цитата) | Разница.
