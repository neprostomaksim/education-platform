*При серьёзном внедрении встаёт важный выбор: где «живёт» модель — в облаке провайдера или на вашем сервере. От этого зависят безопасность, стоимость и сложность. Разберём плюсы и минусы, чтобы решать осознанно.*

## Два варианта

- **Облачные (ChatGPT, Gemini, Claude …)** — модель работает на серверах провайдера, вы отправляете запросы через интернет. Это всё, чем мы пользовались на воркшопе.
- **Локальные (on-premise)** — открытая модель работает **на вашем железе**, внутри компании; данные не покидают контур.

## Облачные: плюсы и минусы

**Плюсы:** дёшево или бесплатно; самые сильные модели; ничего не надо поддерживать; быстрый старт; всегда актуальная версия.
**Минусы:** данные уходят в облако → **нужно обезличивание**; лимиты и тарифы; зависимость от провайдера; чувствительное нельзя грузить «как есть».

## Локальные: плюсы и минусы

**Плюсы:**
- **Закрытый контур** — данные не покидают компанию;
- можно грузить **любые файлы без обезличивания** (реальные УНП, суммы, договоры);
- соответствие строгим требованиям безопасности;
- нет внешних лимитов, полный контроль.

**Минусы:**
- **Сложность внедрения** — нужны ИТ-специалисты и настройка;
- **Дороговизна** — свой сервер с мощными видеокартами (GPU), большим объёмом оперативной памяти и производительным процессором;
- **Поддержка и обслуживание** — обновления, отказоустойчивость, электричество;
- качество открытых моделей **обычно ниже** топовых облачных; долгий запуск.

## Сравнение (коротко)

| | **Облачные** | **Локальные** |
|---|---|---|
| Стоимость старта | низкая / бесплатно | высокая (сервер, GPU, ОЗУ) |
| Данные | уходят в облако (нужно обезличивание) | остаются внутри, любые файлы |
| Качество моделей | топовое | обычно ниже |
| Поддержка | не нужна | нужны свои спецы |
| Скорость запуска | минуты | недели/месяцы |

## Когда что выбирать

- **Старт и большинство задач** — **облако + обезличивание**. Дёшево, сильно, быстро.
- **Локальные** — когда данные критичны и их **нельзя** обезличивать/выпускать наружу, есть бюджет и ИТ-ресурсы, большой поток чувствительных документов.
- **Гибрид** (частый выбор): рутина и черновики — в облаке (обезличенно), самое чувствительное — на локальной модели.

> ⚖️ **Для аудиторской фирмы на старте** почти всегда правильно: **облако + строгое обезличивание** (Модуль 2 и урок «Контроль»). Локальная модель — осознанное решение под конкретную потребность и бюджет, обычно на зрелом этапе.

