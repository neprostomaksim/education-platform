## Три вопроса, которые всё расставляют по местам

1. **Промпт или агент?** Промпт — разовый запрос. Агент (Gem) — та же инструкция, **сохранённая ролью**: собрал один раз — пользуешься всегда.
2. **Текст или числа?** Текст и документы → ИИ (Gem / NotebookLM). Точные вычисления и сверки → **макросы** в Excel. Правило: **арифметику — машине, суждение — человеку.**
3. **Обычный чат или NotebookLM?** Обычный Gem отвечает «из головы» и может выдумать. **NotebookLM** отвечает **только по загруженным документам и даёт ссылку** — почти не врёт. Для точных цитат (НПА) — NotebookLM.

## Чем инструменты отличаются (коротко)

- **Gem-агент** — универсал по тексту: пишет, извлекает, объясняет, сравнивает. Данные вставляете текстом.
- **NotebookLM** — «спроси у своих документов»: отвечает по источникам со ссылкой (grounding). Excel не принимает — только PDF/текст/DOCX.
- **Макросы** — точный счёт в Excel, работают **локально**: данные никуда не уходят.

## Главные принципы (держим в голове весь День 2)

- 🧑‍🎓 **ИИ — как толковый стажёр:** быстрый и старательный, но может **выдумать** (галлюцинации). Важное всегда проверяем.
- 🔒 **Обезличивание перед облаком:** данные клиента (наименования, УНП, суммы, ФИО) уходят только в виде токенов; карта замен — локально.
- ✍️ **ИИ готовит черновик — решение и суждение остаются за человеком.**

