ПРАВИЛА: нет данных (ответственный, срок) — плашка [уточнить], не придумывай.
ФОРМАТ (без вступлений): заголовки блоков; протокол — с таблицей задач.
```

## Агент 3. Аналитическая записка для решения

Из сырых тезисов/цифр агент собирает короткую записку под управленческое решение: суть, варианты, за/против, рекомендация с оговорками.

```prompt
