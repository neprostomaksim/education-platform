## Принцип: начинать узко, не «внедрять ИИ вообще»

Провальный путь — «давайте все начнём пользоваться ИИ». Рабочий путь — выбрать **1–2 частые, безопасные, хорошо очерченные задачи** и довести их до результата, а потом расширять. Хорошие кандидаты на пилот: суммаризация документов, черновики писем, разбор договоров, подготовка совещаний — всё это вы уже собрали.

## Дорожная карта (4 этапа)

| Этап | Что делаем | Результат |
|---|---|---|
| **1. Пилот** | 1–2 задачи, 2–3 человека, обезличенные данные, готовые агенты с воркшопа | Проверенная польза на реальной рутине |
| **2. Стандарт** | Закрепить лучшие промпты как общие Gem, описать «как правильно», задать правила безопасности | Единый инструментарий, а не «кто как умеет» |
| **3. Масштаб** | Обучить остальную команду, назначить ответственного, собрать частые вопросы | ИИ в ежедневной работе участка/отдела |
| **4. Развитие** | Новые задачи под агентов, обновление промптов, обмен находками | Растущая библиотека инструментов фирмы |

## Роли внедрения

- **Спонсор (руководитель):** задаёт приоритет, выделяет время на пилот, снимает барьеры (VPN, аккаунты, политика по макросам).
- **Драйвер/ответственный за ИИ:** ведёт библиотеку общих Gem, отвечает на вопросы, следит за безопасностью. Не обязательно технарь.
- **Пилотная группа:** 2–3 человека, которые обкатывают задачи и дают обратную связь.

## Два трека внедрения: люди и технологии

Внедрение ИИ идёт по **двум параллельным трекам**. Если тянуть только один — не приживётся:

| | **Трек «Люди и процессы»** | **Трек «Технологии и автоматизация»** |
|---|---|---|
| Про что | Чтобы сотрудники **захотели и умели** пользоваться | Чтобы **инструменты работали** надёжно и безопасно |
| Кто ведёт | Спонсор + драйвер | Драйвер + (при усложнении) разработчик |
| Задачи | обучение, стандарт промптов, снятие страхов, мотивация | выбор задач, сборка агентов, оценка качества, guardrails, интеграции |
| Риск, если забыть | «купили, но никто не пользуется» | «пользуются, но ИИ врёт / утечка данных» |

Руководитель отвечает за **оба**: людей — мотивировать и обучить, технологии — довести до надёжности.

## Технический трек: как строить ИИ-автоматизации и продукты

Это **не** «сразу заказать большой ИТ-проект». Правильный путь — от простого готового инструмента к сложному продукту, и только когда простого не хватает. Жизненный цикл любой ИИ-автоматизации:

1. **Выбор задачи — трезво.** Не всякую задачу стоит автоматизировать. Прогоните через фильтр из «Конструктора агентов»: ✅ подходит для ИИ · ⚠️ частично (часть — вручную/макросом) · ❌ не для ИИ (точный счёт, актуальные НПА). Автоматизировать редкий или плохо выстроенный процесс — деньги на ветер.
2. **Данные.** Что подаём на вход? Готовы ли данные (единый формат, обезличены, доступны)? Нет данных — нет автоматизации.
3. **Прототип на готовом (no-code).** Сначала соберите **Gem или NotebookLM** — это прототип за час, без разработчиков. Бо́льшая часть задач фирмы закрывается здесь, и до «продукта» дело не доходит.
4. **Оценка качества (шаг, который все пропускают).** Соберите 5–10 **тестовых примеров с эталонным ответом** («золотой набор») и прогоните агента: где выдумывает, где теряет данные. Без этого вы не знаете, работает агент или лишь убедительно выглядит.
5. **Guardrails (ограничители).** Впишите в промпт правила против выдумок («нет данных — плашка», «не подбирай счета сам»), сузьте область работы, оставьте **человека в контуре** на проверке. Для чувствительного — обезличивание на входе.
6. **Build vs Buy — когда нужен настоящий ИТ-продукт.** Gem хватает, пока: одна роль, ручной вход-выход, без интеграций. **Полноценный продукт с разработчиком** нужен, когда: требуется доступ к вашим системам (1С, база, API), большой поток документов, поиск по всей базе знаний (RAG), логирование и роли. Тогда — ТЗ и подрядчик, но уже на сценарии, **проверенном на прототипе**.
7. **Внедрение и мониторинг.** Версионируйте промпты, собирайте обратную связь, ведите библиотеку, назначьте ответственного. Агент — не «поставил и забыл»: модели и задачи меняются.

> 🧭 **Правило:** сложность инструмента наращивают под задачу, а не наоборот. Сначала докажите пользу на Gem-прототипе — потом вкладывайтесь в ИТ-продукт. Агенты-помощники для этого трека (стратег, аудит процессов, ТЗ на продукт) — в уроке «Управленческие ИИ-агенты».

## Пошаговый план внедрения ИИ в вашей фирме

Готовый порядок действий — просто идите по шагам сверху вниз. Сроки — ориентир для средней фирмы; маленькой можно сжать, шаги те же. Справа — как понять, что шаг пройден.

**Неделя 1 · Подготовка**
1. **Назначьте ответственного за ИИ** (драйвера) — не обязательно технаря. → *есть человек с именем.*
2. **Выберите 1–2 задачи для пилота.** Прогоните задачи фирмы через агента «Аудит процессов под ИИ» → возьмите 1–2 из топ-3. Критерий: часто · безопасно · очерчено. → *задачи записаны.*
3. **Дайте доступ пилотной группе** (2–3 человека): аккаунты Gemini/NotebookLM, VPN, разрешение макросов. → *у всех открывается и работает.*

**Недели 2–3 · Пилот**
4. **Соберите агентов** под выбранные задачи — готовые с воркшопа или через «Конструктор агентов». → *агент отвечает по делу.*
