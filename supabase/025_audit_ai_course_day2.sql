## Деанонимизация: как ИИ может «вычислить» клиента — и как это предотвратить

Частый и правильный вопрос: «мы заменили имена на токены — этого достаточно?» **Нет.** Замены имён мало: ИИ может восстановить, о ком речь, по **косвенным следам**. Вот четыре канала утечки и что делать с каждым.

**1. Смысловые маркеры (контекст).** Уникальные факты выдают компанию даже без названия: «крупнейший производитель калийных удобрений в регионе», «единственный поставщик турбин для ТЭЦ-5», редкая должность («директор департамента цифровых платформ макрорегиона Центр»).
➡️ *Обобщайте формулировки:* убирайте отраслевые и монопольные признаки, редкие должности заменяйте родовыми («производитель», «поставщик оборудования», «руководитель подразделения»).

**2. Числовой отпечаток.** Уникальные точные суммы (1 423 567 890,12 руб.) могли светиться в новостях, госзакупках, публичной отчётности. А соотношение выручки, прибыли, дебиторки и основных средств — это «финансовый отпечаток пальца», который ИИ сопоставит с открытыми балансами отрасли.
➡️ *Масштабируйте суммы коэффициентом* (`AnonymizeAmounts` из Модуля 2 — суммы остаются числами, но не настоящими), не оставляйте узнаваемых точных значений, агрегаты передавайте огрублённо.

**3. Метаданные и «мусор» файла.** При загрузке **файла** (DOCX/PDF/XLSX) ИИ видит не только текст: свойства файла (автор, организация, путь `...\Клиенты\Ромашка\Отчёт.docx`), историю правок (Track Changes), скрытые и удалённые фрагменты, текст под чёрной «замазкой» в PDF, скрытые столбцы Excel.
➡️ *Не грузите файл — вставляйте текст* (Copy → Paste): это обрубает метаданные, историю и скрытые слои. Если файл обязателен — очистите свойства (Word: «Инспектор документов»), пересохраните или «распечатайте в PDF», **не замазывайте, а удаляйте** текст, используйте `ExportSafeCopy` (свежий файл без карты замен и без истории исходника).

**4. Лингвистический и гео-след.** Топонимы (малые города, станции отгрузки, порты), внутренние артикулы («задвижка X-200-P»), названия ИТ-систем (`SAP-HR-PROD`, `1С-УПП-Завод`) сужают круг до одной компании.
➡️ *Вычищайте гео-привязки, артикулы и коды систем* либо обобщайте их.

### Пошаговая инструкция: подготовка документа перед загрузкой в ИИ

Делайте по порядку **каждый раз**, когда готовите документ клиента для облачного ИИ (Gemini, ChatGPT, NotebookLM). Это ручная процедура — её не поручают самому ИИ (иначе данные уже уйдут в облако).

**Шаг 1. Работайте с КОПИЕЙ.** Никогда не редактируйте оригинал — сделайте отдельную копию «для ИИ». Оригинал с реальными данными остаётся только у вас.

**Шаг 2. Замените прямые идентификаторы на токены.** Пройдите по тексту и замените на условные метки:
- наименования организаций → `КОМПАНИЯ_001`, `КОМПАНИЯ_002`;
- ФИО → `ФИО_001`; должности конкретных людей → обобщённо;
- УНП / ИНН → `УНП_001`; номера счетов → `СЧЁТ_001`;
- адреса, телефоны, e-mail, номера договоров и дел, ведущие к клиенту.

Одинаковую сущность помечайте одним и тем же токеном (чтобы связи в тексте сохранились). **Карту замен** (какой токен что означает) держите только у себя — в облако её не грузят никогда. Для Excel это делает макрос `Anonymize` (Модуль 2).

**Шаг 3. Обезличьте суммы коэффициентом.** Уникальные точные суммы (напр. 1 423 567 890,12 руб.) могли светиться в новостях, госзакупках, публичной отчётности. Умножьте все суммы на один секретный коэффициент: они останутся числами (ИИ сможет считать пропорции), но реальных значений не покажут. Excel — макрос `AnonymizeAmounts`, обратно `UnscaleAmounts`. Если суммы для задачи не важны — просто удалите или огрубите их.

**Шаг 4. Обобщите смысловые маркеры.** Уберите уникальные факты, выдающие компанию даже без названия: «крупнейший производитель калийных удобрений в регионе» → «производитель»; монопольное положение; редкие должности («директор департамента цифровых платформ макрорегиона Центр») → родовые («руководитель подразделения»); узкую отраслевую специфику, если она не нужна для задачи.

**Шаг 5. Уберите гео- и технические следы.** Топонимы (малые города, станции отгрузки, порты), внутренние артикулы («задвижка X-200-P»), названия ИТ-систем (`SAP-HR-PROD`, `1С-УПП-Завод`) — удалите или обобщите. Они сужают круг до одной компании.

**Шаг 6. Грузите ТЕКСТ, а не файл.** Скопируйте очищенный текст и вставьте в чат (Copy → Paste). Это ключевой приём: он обрубает всё, что прячется внутри файла — свойства (автор, организация, путь `...\Клиенты\Ромашка\Отчёт.docx`), историю правок (Track Changes), скрытые и удалённые фрагменты, текст под чёрной «замазкой» в PDF, скрытые столбцы Excel.

**Шаг 7. Если файл обязателен — вычистите метаданные.** У документа есть «невидимая» информация: автор, организация, путь к файлу, примечания, история правок (Track Changes), скрытый текст.

> ⚠️ **Важно:** обычная копия файла (Ctrl+C / Ctrl+V, «Дублировать») **сохраняет все метаданные** — это точная копия. Значит, «копия для правок» из Шага 1 их НЕ чистит. Нужна специальная операция ниже.

**Как убрать метаданные в Проводнике Windows (без Office):**
1. Найдите файл в Проводнике → щёлкните **правой кнопкой** → **«Свойства»**.
2. Вкладка **«Подробно»** → внизу ссылка **«Удаление свойств и личной информации»**.
3. Выберите **«Создать копию с удалением всех возможных свойств»** → **ОК**. Рядом появится **очищенная копия** — грузите в ИИ именно её.

**PDF:** **не «замазывайте» чёрным прямоугольником** — под ним текст остаётся и копируется; **удаляйте** его в PDF-редакторе. Чтобы заодно обрубить метаданные — пересоздайте файл: «Печать» → принтер **«Microsoft Print to PDF»** → сохранить.

**Excel:** сначала макрос `ExportSafeCopy` (свежий файл без листа «Map» и без истории), затем по этой копии — чистка свойств через Проводник.

> ✅ **Проще всего — вообще не грузить файл (Шаг 6):** вставленный **текст** метаданных, истории правок и скрытых слоёв не несёт. Чистка файла нужна, только когда без файла никак.

**Шаг 8. Грузите только нужный фрагмент**, а не весь документ. Меньше данных — меньше следов.

**Шаг 9. Проверьте глазами перед отправкой.** Быстро перечитайте: не осталось ли имён, УНП, узнаваемых сумм, гео-привязок. Проверяет **человек** — не сам ИИ.

> ⚖️ **Принцип:** обезличивание — это не «стереть имя», а **разорвать все ниточки** к клиенту: смысловые, числовые, файловые, языковые. Полная гарантия — только не грузить чувствительное в облако; для критичного — локальные модели (урок «Локальные ИИ-модели vs облачные») и макросы.

## ИИ-политика фирмы (шаблон)

**Можно:**
- обезличенные данные в бесплатные ИИ-сервисы;
- черновики (письма, выжимки, разбор договоров, замечания) — с обязательной проверкой человеком;
- методологию фирмы (памятки, нормы, справочники) — как файлы-знания Gem.

**Нельзя:**
- данные клиента (наименование, УНП, счета, ФИО, суммы) в облако без обезличивания;
