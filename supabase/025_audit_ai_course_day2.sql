## Саботаж неизбежен — и это нормально

Часть команды будет сопротивляться ИИ. Причины почти всегда одни и те же:
- страх, что ИИ **заменит** и человек потеряет работу;
- недоверие («он же врёт», «это игрушка»);
- нежелание учиться новому, выходить из зоны комфорта;
- «мы всегда так работали — и всё нормально»;
- страх показаться некомпетентным, если «не получится».

Это **естественная реакция на изменения**, а не злой умысел. Признайте её открыто и не давите силой — давление усиливает сопротивление.

## Как работать с сопротивлением

- Показывать **личную выгоду** (экономия времени), а не «приказ сверху».
- Снимать страх замены: ИИ убирает **рутину**, а решение, суждение и ответственность остаются за человеком.
- Давать пробовать **безопасно** — без наказания за ошибку в эксперименте.
- Делать **маленькие победы видимыми** для всей команды.

## Приём: «главного саботажника — в лидеры внедрения»

Найдите человека, который **громче всех против** и активнее всех сопротивляется. Поставьте именно его **ответственным за внедрение** (или ключевым в пилотной группе). Парадокс работает: получив ответственность и статус, человек разворачивает энергию с сопротивления на внедрение — начинает не мешать, а **активно тащить** (чтобы доказать, что справится, и потому что теперь это «его» проект). Бонус: он лучше всех знает слабые места и возражения коллег — и закроет их изнутри.

