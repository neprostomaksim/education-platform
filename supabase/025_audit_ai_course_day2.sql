## Что это и зачем руководителю

Wispr Flow — приложение для **голосового ввода**. Вы зажимаете горячую клавишу, говорите обычным голосом, отпускаете — и текст появляется там, где стоит курсор. ИИ внутри убирает слова-паразиты, расставляет знаки препинания и форматирует. Поддерживает русский язык.

Где пригодится: продиктовать бриф агенту («Тип 1, письмо клиенту, запросить ОСВ за 2024, срок 5 дней»), надиктовать длинный промпт, черновик письма, заметки к совещанию — руки свободны, получается быстрее.

