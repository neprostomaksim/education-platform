### Аудиторская выборка — `Sampling`
**Что делает:** формирует аудиторскую выборку из совокупности тремя методами: случайная, монетарная (вероятность пропорциональна сумме), систематическая (с шагом).
**Как проверить:** совокупность на **первом листе** → `Alt+F8` → `Sampling` → укажите метод и объём. Создаёт лист **Sample_Result**.
