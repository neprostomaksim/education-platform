## 🧮 Макросы (Excel) — что делают и как проверить

Все макросы — **только для Excel на Windows**, работают **локально** (данные не уходят). Как добавить: `Alt+F11` → **Insert → Module** → вставьте код (из урока «Код макросов», День 1) **или** File → Import File → `.bas` → закройте редактор → `Alt+F8` → выберите процедуру → **Выполнить**. Работать на **обезличенных/учебных** данных.

### Обезличивание — `Anonymize` / `AnonymizeAmounts` / `ExportSafeCopy` / `Restore` / `UnscaleAmounts`
**Что делает:** прячет данные клиента перед загрузкой в облако: текст и идентификаторы → токены, суммы → ×секретный коэффициент; `ExportSafeCopy` сохраняет чистую копию без листа «Map».
**Как проверить:** выделите текстовые столбцы (наименование, УНП, счёт) → `Anonymize`; выделите столбец сумм → `AnonymizeAmounts`; затем `ExportSafeCopy`. Вернуть у себя: `Restore` (токены), `UnscaleAmounts` (суммы). Создаёт лист **«Map»** — его в ИИ не грузить.
📎 [Anonymize.bas](/lesson-files/Anonymize.bas) + [учебный файл (реестр контрагентов)](/lesson-files/Обезличивание_учебный_файл.xlsx)

### JET: тесты проводок — `RunAllTests`
**Что делает:** прогоняет журнал проводок через 13 тестов (проводки выходного дня, круглые суммы, Дт≠Кт, сторно, счёт «999», тест Бенфорда) и помечает подозрительные строки.
**Как проверить:** журнал на **первом листе**, шапка со столбцом «Дата» → `Alt+F8` → `RunAllTests`. Создаёт листы **Flags**, **JET_Data**, **JET_Settings**, **JET_Benford**. Строку из «Flags» отдают ИИ-агенту «JET: вывод по тесту».
📎 [JET_Tests.bas](/lesson-files/JET_Tests.bas) + [учебный файл с аномалиями](/lesson-files/JET_учебный_файл_с_аномалиями.xlsx)

### Сверка ОСВ — `TB_Check`
**Что делает:** арифметическая проверка оборотно-сальдовой ведомости — сходятся ли обороты и сальдо по каждому счёту.
**Как проверить:** ОСВ на **первом листе**, шапка со столбцом «Код» → `Alt+F8` → `TB_Check`. Создаёт лист **TB_Flags** с расхождениями.
