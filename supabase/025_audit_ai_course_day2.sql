**🎯 База:** определите, какие ваши задачи в принципе нельзя решать в облаке даже с обезличиванием — это кандидаты на локальную модель (если такие есть).
**🚀 Уровень 2:** прикиньте, что для вашей фирмы сейчас дешевле и разумнее — облако с обезличиванием или локальная модель, и почему.
> 🤔 **Перенос:** есть ли у вас данные, которые нельзя обезличить в принципе? Если да — это единственный веский повод смотреть в сторону локальной модели.

## Что важно запомнить

- ☁️ **Облачные:** дёшево, сильно, быстро — но данные уходят (нужно обезличивание).
- 🏠 **Локальные:** закрытый контур, любые файлы без обезличивания — но дорого (сервер, GPU, ОЗУ), сложно, нужна поддержка, качество обычно ниже.
- ⚖️ **Старт — облако + обезличивание;** локальные — под критичные данные и при бюджете; часто **гибрид**.
