Когда в процессе несколько ИИ-шагов и инструментов, нужен **оркестратор** — «дирижёр», который:
- по порядку запускает нужных агентов и инструменты,
- передаёт результат одного шага на вход следующего,
- ходит во внешние системы (1С, база, API) за данными и складывает итог обратно.

**Пример — процесс «проверка контрагента»:** оркестратор берёт из 1С реквизиты → агент извлекает условия договора → инструмент сверяет с базой/списком → агент готовит проект заключения → результат кладётся обратно в систему. Человек только проверяет и подписывает итог.

Оркестратор — это уже **ИТ-разработка** (код, интеграции, логика), а не Gem, собранный за минуту.

## Когда переходить на уровень 2

Только когда одновременно:
- сотрудники **уже живут с ИИ** на уровне 1 (есть опыт и доверие);
- процесс **понятен и упорядочен** (не автоматизируем хаос);
- есть **повторяемый поток** (много однотипных документов/операций);
- виден **выигрыш** от сквозной автоматизации.

> 🧭 Признак готовности: сотрудники **сами** говорят «вот тут между моими задачами всё можно связать». Это и есть сигнал к автоматизации процесса.

## Как строить (жизненный цикл автоматизации)

1. **Выбор задачи — трезво.** Прогоните через фильтр «Конструктора агентов»: ✅ подходит · ⚠️ частично · ❌ не для ИИ (точный счёт, актуальные НПА).
2. **Данные.** Готовы ли (единый формат, обезличены, доступны)? Нет данных — нет автоматизации.
3. **Прототип на готовом (no-code).** Сначала Gem/NotebookLM — прототип за час, без разработчиков. Бо́льшая часть задач закрывается здесь.
4. **Оценка качества** (шаг, который все пропускают). 5–10 тестовых примеров с эталоном → где выдумывает, где теряет данные.
5. **Guardrails.** Правила против выдумок, узкая область, **человек в контуре**, обезличивание на входе.
6. **Build vs Buy** (см. ниже).
7. **Мониторинг.** Версии промптов, обратная связь, ответственный. Агент — не «поставил и забыл».

