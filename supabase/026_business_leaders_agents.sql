## Чем агент отличается от обычного промпта

Всё, что вы делали в прошлых блоках, — это разовые запросы: написали промпт, получили ответ, закрыли чат. Для задачи, которая повторяется каждую неделю, это лишняя работа.

| | Разовый промпт | Агент |
|---|---|---|
| Инструкция | пишете заново каждый раз | зашита один раз при настройке |
| Что даёте на вход | инструкцию + данные | только данные |
| Стабильность результата | зависит от того, как сформулировали сегодня | одинаковый формат на всех запусках |
| Кому подходит | разовая задача | задача, которая повторяется |

Разбор встреч — идеальный кандидат в агенты: формат нужен один и тот же, а встреч в неделю несколько.

## Почему именно NotebookLM, а не Gemini или ChatGPT

Чат-модель не расшифровывает аудиофайл — ей нужно уже готовое текстовое содержание. **NotebookLM** (notebooklm.google.com, бесплатный сервис Google) принимает аудио как источник и расшифровывает его сам. Это единственная причина выбора инструмента здесь — во всех остальных уроках блока мы используем Gemini.

Практические ограничения, которые стоит знать заранее:
- **до 200 МБ на файл** — это несколько часов записи; совещание на весь день разбейте на части;
- подходят обычные форматы (mp3, m4a, wav) — то, что отдаёт диктофон телефона или запись созвона;
- ответы приходят **со ссылкой на момент записи** — любую фразу агента можно проверить, не переслушивая всё.

## Как настроить агента — по шагам

1. **Получите запись.** Диктофон на телефоне, запись Zoom / Google Meet / Teams или аудио со встречи.
2. Откройте **notebooklm.google.com** → **Create new** (новый блокнот) → **Add source** → загрузите аудиофайл.
3. Дождитесь, пока NotebookLM **сам расшифрует запись** — печатать вручную ничего не нужно.
4. Задайте роль агента: **«Настройка чата» → «Свой вариант»** → вставьте промпт ниже и сохраните.
5. Спрашивайте: «сделай сводку встречи», «какие задачи и кто ответственный», «какие вопросы остались открытыми».

Блокнот с этой настройкой создаётся один раз — дальше вы просто добавляете в него новые записи.

### Готовый промпт

```prompt
РОЛЬ
Ты — ассистент руководителя. Разбираешь расшифровку записи разговора (совещание, встреча, созвон) СТРОГО по её содержанию. Ничего не додумываешь.

ВХОД: загруженная в NotebookLM аудиозапись или её расшифровка (это источник блокнота, а не текст в чат).

ЗАДАЧА
1. Суть разговора — 3–5 предложений: о чём и к чему пришли.
2. Ключевые моменты и принятые решения — списком.
3. Задачи — таблица «Задача | Ответственный | Срок» (только то, что прозвучало).
4. Вопросы: ОТКРЫТЫЕ (не решены, требуют возврата) и ЗАКРЫТЫЕ (решены на встрече).

ПРАВИЛА (против выдумок)
- только то, что есть в записи; не прозвучало — «не указано» / «ответственный не назван»;
- существенное (суммы, даты, договорённости) приводи дословно;
- не выдумывай задачи и сроки, которых не было;
- не приписывай слова не тому участнику; кто сказал — неясно, так и пиши;
- не выдавай обсуждение за решение, если решение не было принято.
ФОРМАТ (без вступлений): четыре блока по порядку.
```

### Почему в промпте так много запретов

Блок «ПРАВИЛА» — это не перестраховка, а основная часть работы. Модель по умолчанию стремится выдать «красивый полный протокол»: если ответственный не назван — подставит самого активного участника, если срок не прозвучал — напишет «до конца недели». Такой протокол выглядит убедительнее правдивого и именно поэтому опаснее: вы разошлёте задачи, которых никто не брал.

Отдельно про строку «не выдавай обсуждение за решение». Это самая частая ошибка на управленческих встречах: фразу «ну давайте, наверное, попробуем через месяц» модель охотно записывает в принятые решения. Явный запрет заставляет её оставить это в разделе открытых вопросов — там, где оно и должно быть.

### Как адаптировать под себя

Скопируйте промпт, вставьте в **обычный чат Gemini** и попросите: «Адаптируй этот промпт под меня. Добавь то, что важно именно мне: [перечислите сами]». Что обычно дописывают руководители:

1. **Отдельный блок «Договорённости с клиентом»** — если встречи в основном внешние.
2. **«Кто кому что пообещал»** — отдельным списком, помимо формальных задач.
3. **Риски по срокам** — где прозвучали сомнения в реалистичности дедлайна.
4. **Свой формат протокола** — если в компании принят фиксированный шаблон, опишите его прямо в блоке ФОРМАТ.
5. **Разделение по проектам** — если на планёрке обсуждают несколько направлений подряд.

