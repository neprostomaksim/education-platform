## Практика

*Если вы проходите урок самостоятельно, а не на занятии, — все пять ролей ваши.*

**База.** Возьмите свой реальный продукт — или направление, которое обдумываете, — и впишите его в блок ВХОД промпта Агента 1 вместо квадратных скобок. Прогоните цепочку целиком через пять чатов, каждый раз руками заполняя ВХОД следующего промпта. Не помогайте агентам подсказками между звеньями и не дописывайте ничего вторым сообщением: задача первого прохода — увидеть цепочку такой, какая она есть. В конце прочитайте блок 【НА ЧЁМ ЭТО ДЕРЖИТСЯ】: сколько допущений накопилось за пять шагов?

**Вариация (то же, другое условие).** Прогоните ту же цепочку ещё раз, изменив на первом звене **одну вещь**: попросите Агента 1 выбрать приоритетным **другой** сегмент из тех, что он сам назвал. Всё остальное не трогайте. Сравните два финальных анонса. Насколько сильно разошёлся результат от одного изменённого решения в самом начале — и что это говорит о цене вводной, которую вы даёте команде?

**Вопрос на перенос.** В этой цепочке пять ролей выстроены линейно: каждый работает после предыдущего. Какие ваши реальные задачи так же линейны, а какие устроены иначе — где двое должны работать параллельно, а третий сводить их результаты? Что в бланке контекста придётся изменить, чтобы он поддерживал схождение двух веток в одну?

**Задача с подвохом.** В цепочке нет звена, которое проверяет **исходные данные** — Агент 5 стоит в конце и проверяет то, что уже сделано. Соберите шестого агента, который встанет между звеньями 1 и 2 и будет проверять работу аналитика до того, как ошибка размножится. Пошаговой инструкции нет: решите сами, что он должен проверять, какие поля бланка ему нужны, что он делает при обнаружении проблемы и куда девается его собственный вывод.

