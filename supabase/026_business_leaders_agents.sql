## Почему Gem в Gemini, а не NotebookLM

В прошлом уроке мы брали NotebookLM ради расшифровки аудио. Здесь задача другая — выдать на руки готовый длинный текст документа, и инструмент нужен другой.

| | NotebookLM | Gem в Gemini |
|---|---|---|
| Отвечает по загруженным источникам | да | да (файлы в знаниях) |
| Выдаёт длинный готовый документ | плохо: отвечает выжимками со ссылками | да, это его основной режим |
| Постоянная инструкция | настройка чата в блокноте | поле «Инструкции» в Gem |
| Образец всегда под рукой | да | да, прикрепляется в знания Gem один раз |

Для договоров нужен именно **Gem**: образец кладётся в знания один раз, и дальше вы обращаетесь к агенту, не прикрепляя файл заново.

## Как создать агента — по шагам

1. Откройте **gemini.google.com** → в левом меню **«Gems»** → **«Новый Gem»**.
2. В поле **«Инструкции»** вставьте промпт ниже.
3. Дайте имя — например, «Договор поставки, форма компании».
4. Прикрепите в **знания Gem** ваш договор-образец (файл .docx или .pdf).
5. Сохраните.

**Важно: один Gem — один тип договора.** Не сваливайте в знания поставку, услуги и аренду сразу: агент начнёт смешивать формулировки из разных форм, и вы получите гибрид, которого юрист не согласовывал. Нужны три формы — сделайте три Gem, промпт у них будет одинаковый.

### Готовый промпт

```prompt
