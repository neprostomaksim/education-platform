## Один промпт или цепочка

| | Один большой промпт | Цепочка из пяти агентов |
|---|---|---|
| Глубина проработки | поверхностная по всем пунктам сразу | каждый шаг проработан отдельно |
| Видно ли ход рассуждения | нет, только итог | да, на каждом стыке |
| Можно ли вмешаться | только переделать всё целиком | да, на любом звене |
| Где ошибка | непонятно | видно, какое звено ошиблось |
| Затраты времени | 2 минуты | 15–20 минут |

Цепочка дороже по времени, поэтому берут её не всегда. Она оправдана, когда решение важное, а результат каждого шага влияет на следующий: запуск продукта, вход в новый сегмент, пересмотр линейки тарифов.

## Почему передаём результат вручную

Существуют системы, где агенты передают данные друг другу автоматически. Мы делаем это руками, копируя блок из одного чата в другой, и на старте это правильно по трём причинам.

1. **Вы видите, что происходит между звеньями.** Автоматическая передача прячет самое интересное — момент, когда контекст искажается.
2. **Вы можете вмешаться.** Заметили, что аналитик выбрал не тот сегмент, — поправили до того, как ошибка размножилась.
3. **Вы понимаете, что автоматизировать.** Пройдя цепочку руками три раза, вы точно знаете, какие звенья стабильны, а какие требуют человека. Это и есть ответ на вопрос, что можно отдавать в автоматизацию.

Технически всё просто: **пять отдельных чатов** в Gemini или ChatGPT. В каждый уходит одно сообщение — промпт агента, внутри которого вы **своими руками** заполнили блок ВХОД: на первом звене вписали продукт и компанию, на остальных вставили результат предыдущего звена. Отдельные чаты нужны, чтобы роли не смешивались: в одном чате модель начнёт помнить, что она уже была аналитиком, и стратег получится половинчатым.

## Бланк контекста — сердце цепочки

Главное в цепочке — не промпты, а формат, в котором звенья передают друг другу работу. Если каждый агент придумывает свой способ передачи, к третьему шагу половина данных теряется.

Поэтому у всех звеньев **один и тот же бланк**, который только заполняется, но никогда не сокращается:

```
===== КОНТЕКСТ ПРОЕКТА · ЗВЕНО N из 5 =====
Продукт:
Компания:
Сегменты ЦА:
Приоритетный сегмент:
Ключевая боль:
Позиционирование:
Главный оффер:
Тарифы:
Текст анонса:
ДОПУЩЕНИЯ:
ЗАМЕЧАНИЯ:
===========================================
```

Поля, до которых очередь ещё не дошла, помечаются как «— (заполнит звено 3)». Заполненные — переносятся дословно. К пятому звену бланк содержит всю историю работы цепочки.

Два последних поля — самые важные, и в обычных цепочках их не бывает.

**ДОПУЩЕНИЯ** — сюда каждое звено складывает то, что додумало само, потому что данных не хватило. Модель всегда что-то додумывает; вопрос только в том, признаётся она в этом или растворяет догадку в тексте. К концу цепочки вы получаете честный список того, на чём держится результат, — и понимаете, что нужно проверить в реальности, прежде чем действовать.

**ЗАМЕЧАНИЯ** — сюда звено пишет, если не согласно с предыдущим. Без этого поля агент поступит худшим образом: молча перепишет чужой вывод под себя, и вы никогда не узнаете, что позиционирование на пятом шаге отличается от того, что придумал стратег.

