## Как запускать — по шагам

Каждый промпт отправляется **одним сообщением** — вместе с данными внутри. Копируете промпт в текстовый редактор или прямо в поле чата, находите в нём блок ВХОД, руками заменяете квадратные скобки на своё, и только потом отправляете. Ничего дописывать вторым сообщением не нужно.

1. Откройте **пять отдельных чатов** в Gemini или ChatGPT. Назовите их «Звено 1» … «Звено 5», чтобы не перепутать.
2. Скопируйте промпт Агента 1. **Заполните в нём блок ВХОД** — впишите свой продукт, компанию и то, что знаете о клиентах, вместо текста в квадратных скобках. Отправьте одним сообщением в первый чат.
3. В ответе найдите блок между строками `=====`. **Скопируйте только его** — целиком, вместе с обеими рамками.
4. Скопируйте промпт Агента 2. **Замените в нём строку `[СЮДА ВСТАВИТЬ БЛОК …]`** на то, что скопировали. Отправьте одним сообщением во второй чат.
5. Повторите то же для звеньев 3, 4 и 5: скопировать промпт → вставить в него блок от предыдущего звена → отправить.
6. На выходе — финальный анонс, список правок и перечень допущений, которые нужно проверить.

> **Почему промпт правится руками, а не дописывается вторым сообщением.** Так вы физически видите, что именно уходит агенту: где заканчивается инструкция и начинаются данные, что из предыдущего шага доехало, а что потерялось. Это тренирует главный навык работы с агентами — собирать вход осознанно. При передаче вторым сообщением этот шов не виден, и на третьем звене вы уже не понимаете, откуда взялся тот или иной вывод.

**Две частые ошибки на старте:**

1. **Скопировать весь ответ агента вместо блока контекста.** Тогда следующее звено получает и рассуждения, и бланк, начинает спорить с предыдущим агентом вместо работы и теряет формат. Копируется только рамка.
2. **Забыть заменить квадратные скобки.** Агент получит инструкцию с плейсхолдером и либо переспросит, либо — что хуже — начнёт работать с воображаемым продуктом. Перед отправкой пробегитесь по промпту: `[` в тексте остаться не должно.

## Где цепочка ломается

Три места, за которыми стоит следить, — они же три управленческие идеи этого урока.

**1. Ошибка первого звена дороже всех.** Если аналитик выбрал не тот сегмент, все следующие четыре агента честно и качественно отработают на неправильную аудиторию. Никто из них не усомнится: у них нет доступа к исходным данным, есть только то, что передало первое звено. Именно поэтому в реальной работе неверная вводная, отданная в отдел, обходится дороже плохого исполнения — исполнение можно переделать за день, а неделю работы пяти человек не вернуть.

**2. Контекст тает при передаче.** Если не заставить агента переносить строки дословно, он начнёт сокращать: сначала уберёт «Компанию», потом сожмёт три сегмента до одного, потом перескажет боль своими словами — и она станет другой. К пятому звену от исходной задачи остаётся общее впечатление. Правило «переноси дословно, добавляй только в своё поле» существует ровно против этого.

**3. Звено молча правит предыдущее.** Модель, увидев несогласованность, склонна её сгладить: копирайтер тихо подправит оффер, чтобы текст лучше звучал. Формально всё гладко — фактически стратегия изменилась, и никто этого не решал. Поле ЗАМЕЧАНИЯ переводит конфликт из скрытого в явный: разногласие доезжает до вас, а не растворяется по дороге.

