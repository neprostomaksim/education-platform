**Что важно запомнить:**
- Пять узких ролей дают более качественный результат, чем один агент, которому поручили пять задач сразу. Цена — время, поэтому цепочку собирают под важные решения, а не под рутину.
- Главное в цепочке — не промпты, а бланк контекста: единый формат, который только заполняется и никогда не сокращается.
- Поля ДОПУЩЕНИЯ и ЗАМЕЧАНИЯ важнее самих результатов. Первое показывает, на каких догадках держится вывод, второе не даёт разногласиям раствориться по дороге.
- Ошибка первого звена проходит через всю цепочку, и ни одно следующее звено её не заметит — у них нет исходных данных. Ровно так же работает неверная вводная, отданная людям.
- Ручная передача между чатами — не примитивный этап, а способ увидеть, где цепочка ломается. Автоматизировать имеет смысл только те звенья, которые вы уже прогнали руками и знаете как устойчивые.
