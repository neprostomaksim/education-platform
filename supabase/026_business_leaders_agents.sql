## Про безопасность

Аудио уходит в облако Google целиком, и обезличить речь «на лету» невозможно — в отличие от таблицы, где данные можно заменить перед загрузкой. Практический вывод для руководителя:

- **внутренние планёрки** — обычно приемлемо;
- **встречи, где звучат персональные данные, коммерческие условия клиентов или суммы сделок** — оценивайте по правилам работы с данными, принятым в вашей компании; если такие правила не сформулированы, это повод их сформулировать до, а не после;
- участников встречи стоит предупреждать о записи — это не только этика, но и во многих случаях требование закона.

