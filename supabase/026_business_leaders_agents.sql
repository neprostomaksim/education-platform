## Командный формат: пять человек — пять звеньев

На занятии цепочка собирается командой. Каждый участник — **не курьер, а владелец своего звена**: он отвечает не за то, что скопировал блок, а за то, каким получит вход следующий человек.

### Как разделиться

| Сколько вас | Как распределить звенья |
|---|---|
| 5 | по одному звену на человека |
| 4 | один берёт звенья 4 и 5 (копирайтер + контролёр — они смежные) |
| 3 | 1+2, 3, 4+5 |
| 2 | 1+2+3 и 4+5 |
| 6–7 | двое садятся на одно звено, работают **независимо** в своих чатах, потом сравнивают два блока и выбирают, какой пустить дальше |

Последний случай — не запасной, а самый интересный: два человека с одним промптом и одним входом получают разные результаты, и команде приходится выбирать. Именно здесь становится видно, что качество даёт не промпт сам по себе, а то, как его доработали.

**Продукт берите один на команду и реальный** — бизнес или направление кого-то из участников. На выдумывание не тратьте больше минуты: чем понятнее продукт команде, тем предметнее будет разбор в конце.

### Фаза 1. Заточка промпта (все одновременно, ~10 минут)

Никто никого не ждёт: пока звено 1 работает с реальным продуктом, остальные готовят свои промпты. Задача каждого — превратить промпт из урока в **свой**.

**Шаг 1. Допишите промпт под свою роль.** Что стоит добавить:

| Звено | Что усилить в своём промпте |
|---|---|
| 1. Аналитик | Как отличать сегменты: по задаче, по размеру бизнеса, по стадии? Добавьте признак, по которому режете аудиторию именно вы |
| 2. Стратег | Добавьте требование сравнить позиционирование с альтернативой «клиент не делает ничего» — и объяснить, почему наш вариант выигрывает |
| 3. Ценообразование | Добавьте своё правило разрыва между тарифами и запрет на тариф, отличающийся только «объёмом консультаций» |
| 4. Копирайтер | Впишите свой стоп-лист клише и требование к первой строке — по какому признаку читатель узнаёт себя |
| 5. Контролёр | Добавьте свои критерии приёмки: по каким 3–4 пунктам вы бы завернули текст, будь он от подрядчика |

**Шаг 2. Проверьте промпт на заглушке — не дожидаясь настоящего контекста.** Напишите себе фальшивый входной блок из нескольких строк: любой выдуманный продукт, любая боль, любые тарифы. Прогоните на нём своего агента.

Смотрите не на содержание ответа (оно всё равно про выдуманный продукт), а на поведение агента:
- выдал ли он бланк контекста **целиком**, со всеми полями;
- перенёс ли чужие строки дословно или начал их переписывать;
- признался ли в ДОПУЩЕНИЯХ, что данных мало, — или бодро всё додумал;
- уложился ли в формат.

Каждое «нет» — это то, что нужно починить в промпте **сейчас**, пока настоящий контекст ещё не пришёл. Так работает любой человек, собирающий агента: сначала тест на мусорных данных, потом боевой запуск.

### Фаза 2. Сборка цепочки (~20 минут)

Звено 1 отрабатывает на реальном продукте и передаёт блок звену 2 — сообщением в общий чат команды или показывая экран. Дальше по очереди.

Пока ваша очередь не подошла — продолжайте точить промпт: теперь вы уже видите, что выдают звенья выше, и понимаете, чего вам не хватит на входе. Заранее допишите в свой промпт то, что закроет эту нехватку.

**Правило на время сборки:** словами предыдущему звену ничего не объясняем и переделать не просим. Всё, что не устраивает, идёт в поле ЗАМЕЧАНИЯ и едет дальше по бланку. Это неудобно — и именно это неудобство показывает, чего стоит отсутствие обратной связи в реальной цепочке согласований.

### Фаза 3. Разбор (~10 минут)

Звено 5 зачитывает вслух три блока: 【ФИНАЛЬНЫЙ АНОНС】, 【НА ЧЁМ ЭТО ДЕРЖИТСЯ】 и 【СЛАБОЕ ЗВЕНО】. Потом команда отвечает на четыре вопроса:

1. **Дошла ли боль?** Сравните ключевую боль из блока звена 1 с финальным текстом. Она та же самая или по дороге стала другой?
2. **Сколько допущений накопилось** и какое из них опаснее всего, если окажется неверным?
3. **Чья доработка промпта сработала?** Найдите звено, после которого качество блока заметно выросло, и спросите этого человека, что именно он дописал.
4. **Где бы вы поставили человека?** Если бы эту цепочку запускали в компании еженедельно — какое звено можно отдать агенту без присмотра, а какое нельзя ни при каких условиях?

> **Если время осталось**, прогоните цепочку второй раз на том же продукте, разрешив одно новое действие: любое звено может **один раз вернуть работу назад** с замечанием, и предыдущий обязан отреагировать. Сравните результат и потраченное время — это самый короткий способ измерить, сколько стоит право на обратную связь.

