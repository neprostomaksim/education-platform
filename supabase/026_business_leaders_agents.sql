- данных на какое-то поле не хватило — поставь [УТОЧНИТЬ: что именно нужно] и не придумывай;
- реквизиты, которых не было в моём вводе, НЕ переноси из образца молча — это реквизиты чужого контрагента; помечай [УТОЧНИТЬ: ...].

РЕЖИМ «ИЗМЕНИТЬ»
Вход: договор + мой список правок (например: «в п. 4.2 срок оплаты 10 → 30 банковских дней»; «добавить пункт о конфиденциальности после раздела 7»).
Действие: выдай договор с внесёнными правками.
- трогай только названные пункты; весь остальной текст переноси дословно;
- новый пункт вставляй в указанное место и нумеруй по логике образца, а ниже покажи, какие номера сместились;
- если правка противоречит другому пункту (например, срок оплаты в п. 4.2 и в п. 9.1) — не решай сам: правку внеси, а противоречие вынеси в отчёт;
- если в моём запросе есть пометка «только пункты» — выдай не весь договор, а только изменённые пункты с их номерами.

ОТЧЁТ ОБ ИЗМЕНЕНИЯХ — обязателен в конце ответа в режимах «СОБРАТЬ» и «ИЗМЕНИТЬ»
1. Что подставлено и изменено — таблица «Пункт | Было | Стало».
2. Что осталось незаполненным — полный список всех [УТОЧНИТЬ: ...].
3. На что обратить внимание — противоречия между пунктами, смещённая нумерация, внутренние ссылки вида «в порядке п. 5.3», которые после правок перестали указывать на нужный пункт.

ЗАПРЕТЫ
- не добавлять пункты «для полноты», которых я не просил;
- не менять суммы, даты, наименования и реквизиты и не заменять их на более «правдоподобные»;
- не давать юридических оценок и не утверждать, что договор соответствует закону, — это делает юрист;
- не оставлять данные из образца там, где должны стоять мои: пустое поле помечается, а не заполняется чужим значением.

ФОРМАТ ОТВЕТА
Сначала текст договора сплошным блоком — простым текстом, без markdown-разметки, готовым для вставки в Word. Затем «ОТЧЁТ ОБ ИЗМЕНЕНИЯХ». Без вступлений и комментариев от себя.
```

## Как устроен этот промпт

Три вещи в нём делают основную работу — их стоит понимать, чтобы уметь чинить агента, когда он ошибётся.

**1. «Образец неприкосновенен» стоит выше режимов.** Это не вежливая просьба, а рамка для всего остального. Без неё модель считает своей задачей сделать документ лучше: подтянет формулировки к «стандартным», перепишет корявый, но согласованный пункт, добавит раздел о форс-мажоре, потому что «так принято». Каждое такое улучшение — это текст, которого ваш юрист не видел.

**2. Три режима вместо трёх агентов.** Извлечь, собрать, изменить — разные задачи, но образец у них один. Разделение на режимы внутри одного промпта позволяет держать один Gem на тип договора и переключать поведение первым словом запроса.

**3. Отчёт об изменениях — главная защита.** Без него вам придётся вычитывать весь договор целиком, чтобы понять, что агент сделал, — а это ровно та работа, которую вы пытались сэкономить. С отчётом проверка сводится к трём коротким спискам. Особенно важен третий пункт про внутренние ссылки: если вы вставили новый пункт в раздел 5, то фраза «в порядке, предусмотренном п. 5.3» в другом конце договора теперь указывает не туда. Человек этого почти никогда не замечает.

## Что делать с форматированием

Здесь нужна честность: **чат не сохраняет оформление Word**. Шрифты, отступы, колонтитулы, таблица реквизитов в конце — всё это через окно чата не проходит. Промпт сохраняет то, что действительно можно сохранить: структуру, нумерацию и формулировки. Оформление сохраняется на вашей стороне, и есть два рабочих способа.

**Способ 1 — точечная вставка (рекомендуется).** Держите «золотой» шаблон в .docx нетронутым. Просите агента режимом «ИЗМЕНИТЬ» с пометкой **«только пункты»** — он вернёт три-четыре изменённых пункта вместо двадцати страниц. Вы вставляете их в шаблон по одному. Оформление документа при этом вообще не затрагивается, и объём вычитки минимальный.

**Способ 2 — вставка всего текста.** Когда собираете договор с нуля режимом «СОБРАТЬ», копируйте ответ в шаблон через **«Специальная вставка» → «Сохранить только текст»** (`Ctrl+Shift+V`). Это не притащит чужое форматирование из браузера, но стили абзацев придётся применить заново.

Второй способ уместен для новой формы, первый — для повседневной работы. Через месяц вы будете пользоваться почти только первым.

## Как адаптировать под свой бизнес

1. **Список полей в режиме «ИЗВЛЕЧЬ» — это ТЗ агенту.** Что перечислите, то он и вытащит. Ведёте реестр договоров в Excel — приведите список полей в точности к колонкам реестра, и выгрузка ляжет в таблицу без ручного переноса.
2. **Добавьте свои обязательные условия.** Если в компании принято, что в каждом договоре есть пункт о конфиденциальности и о применимом праве, допишите в «ОТЧЁТ ОБ ИЗМЕНЕНИЯХ» четвёртый пункт: «Проверка обязательных условий: конфиденциальность — есть/нет, применимое право — есть/нет».
3. **Зафиксируйте формат данных.** Если у вас суммы всегда пишутся цифрами и прописью, а даты — «01 марта 2026 г.», укажите это прямо в режиме «СОБРАТЬ», иначе агент возьмёт формат из вашего ввода.
4. **Отдельный Gem под договоры контрагентов.** Тот же промпт, но в знаниях лежит не ваша форма, а ваш чек-лист требований — тогда режим «ИЗВЛЕЧЬ» превращается в инструмент разбора входящих договоров.
5. **Не расширяйте роль.** Соблазн дописать «и оцени риски по договору» велик, но это другая задача и другой агент: смешав их, вы получите правки, сделанные «с учётом рисков», то есть самодеятельность в тексте документа.

### Пример использования

**Вводные (режим «ИЗМЕНИТЬ», пометка «только пункты»):** договор поставки по форме компании; правки — срок оплаты в п. 4.2 с 10 на 30 банковских дней, пеня в п. 6.1 с 0,1% на 0,05% за день просрочки.

