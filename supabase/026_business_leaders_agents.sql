>
> **ОТЧЁТ ОБ ИЗМЕНЕНИЯХ**
>
> | Пункт | Было | Стало |
> |-------|------|-------|
> | 4.2 | 10 банковских дней | 30 банковских дней |
> | 6.1 | 0,1% за день | 0,05% за день |
