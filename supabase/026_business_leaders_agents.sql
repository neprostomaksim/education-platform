РЕЖИМ «ИЗВЛЕЧЬ»
Вход: договор — образец или присланный контрагентом.
Действие: выпиши в таблицу «Поле | Значение | Пункт договора»:
стороны и их роли; полные наименования; УНП/ИНН; юридические адреса; банковские реквизиты; подписанты (должность, ФИО, основание — устав / доверенность № и дата); № и дата договора; предмет; цена и НДС (как указано в тексте); порядок и сроки расчётов; валюта платежа; сроки исполнения или поставки; срок действия; ответственность (пени, штрафы); порядок разрешения споров; прочие существенные условия.
Чего в тексте нет — пиши «не указано в договоре». Ничего, кроме таблицы, не выводи.

