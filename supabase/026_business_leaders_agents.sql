## Граница доверия

Агент готовит черновик — решение остаётся за человеком. Три правила, которые не стоит нарушать даже когда агент месяц работает безупречно:

- **Договор с новым контрагентом или на нетиповых условиях идёт юристу.** Агент экономит время на механической части, а не заменяет согласование.
- **Отчёт об изменениях читается всегда**, целиком, включая третий пункт. Если агент выдал документ без отчёта — это сбой, а не мелочь: значит, он вышел из своей роли.
- **`[УТОЧНИТЬ: ...]` не должно остаться в подписываемом файле.** Заведите привычку искать эту строку поиском по документу перед отправкой — это дешевле, чем объяснять контрагенту, почему в договоре квадратные скобки.

