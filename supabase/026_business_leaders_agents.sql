## Практика

**Учебные договоры для практики** (оба обезличены — компании, реквизиты и паспортные данные в них вымышленные):

- 📎 **[Договор № HR-07 на консультационные услуги](/lesson-files/ДОГОВОР_HR-07_консультационные_услуги.docx)** — основной пример. Заказчик — юрлицо, исполнитель — физлицо; есть сумма с авансом, сроки, пеня 0,5%, полные реквизиты обеих сторон.
- 📎 [Учебный договор с контрагентом](/lesson-files/Учебный_договор_с_контрагентом.docx) — договор поставки, если хотите вторую форму.

**База.** Создайте Gem по инструкции выше, положите договор HR-07 в знания и прогоните **режим «ИЗВЛЕЧЬ»**. Проверьте таблицу по тексту договора: все ли значения на месте, указаны ли номера пунктов и честно ли помечено «не указано в договоре» там, где условия действительно нет.

**Вариация 1 — собрать новый договор.** Тот же агент, тот же образец, но **режим «СОБРАТЬ»**: подставьте другого исполнителя, дав данные намеренно неполными — например, без банковских реквизитов и без паспортных данных. Правильное поведение: на этих местах стоит `[УТОЧНИТЬ: ...]`, и они перечислены в отчёте. Ошибка, которую нужно поймать: агент молча оставил в новом договоре реквизиты Соколовой М. А. из образца — то есть подставил в ваш документ постороннего человека вместе с его паспортом и счётом. В договоре с физлицом эта ошибка стоит дороже всего, поэтому проверяйте раздел «ИСПОЛНИТЕЛЬ» первым.

**Вариация 2 — изменить пункты.** Режим **«ИЗМЕНИТЬ»** с пометкой «только пункты». Список правок: срок передачи результата (п. 1.5) перенести на 30 сентября 2026 года, пеню (п. 4.1) снизить с 0,5% до 0,1%, аванс (п. 2.3) увеличить с 1200 до 1800 рублей. Агент должен вернуть три пункта и отчёт. Смотрите на третью строку отчёта: заметил ли он, что после переноса срока в п. 1.5 дата авансового платежа из п. 2.3 (5 августа) оказалась почти за два месяца до сдачи работы — формально это не запрещено, но условие стоит пересмотреть.

**Вопрос на перенос.** Промпт держится на связке «неприкосновенный образец + режимы + отчёт об изменениях». Какая часть этой конструкции переносится на **другой** документ по образцу — приказ, коммерческое предложение, регламент, — а какая нет? И почему для договора отчёт об изменениях обязателен, а для коммерческого предложения им, скорее всего, можно пренебречь?

**Задача с подвохом.** Контрагент прислал свою редакцию вашего договора и утверждает, что «поправил только реквизиты и пару формулировок». Проверять двадцать страниц глазами вы не будете. Пошаговой инструкции нет — придумайте, как поручить эту проверку агенту: какой режим использовать, что подать на вход и в каком виде вы хотите получить ответ, чтобы увидеть **все** расхождения, включая тихо удалённый пункт.

