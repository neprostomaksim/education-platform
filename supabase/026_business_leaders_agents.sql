## Практика

**База.** Запишите на диктофон короткую летучку (2–3 минуты) — или проговорите вслух сами, изображая совещание из трёх участников. Загрузите в NotebookLM, настройте агента по промпту выше и получите разбор. Проверьте по своей памяти: не появилось ли в таблице задач того, чего не звучало?

**Вариация (то же, другое условие).** Возьмите запись, где **решение не было принято** — обсуждение зашло в тупик или отложилось. Тот же агент, другой вход. Сравните: попал ли этот вопрос в «Ключевые моменты и принятые решения» (ошибка) или в «Открытые вопросы» (правильно)? Если агент выдал обсуждение за решение — усильте формулировку запрета и прогоните снова.

**Вопрос на перенос.** Промпт держится на четырёх блоках ЗАДАЧИ и пяти правилах против выдумок. Что из этой конструкции сработает на **другой** задаче с NotebookLM — например, на разборе большого отчёта подрядчика, — а что придётся менять? Почему блок «ПРАВИЛА» переносится почти без изменений, а блок «ЗАДАЧА» переписывается целиком?

**Задача с подвохом.** У вас три записи с одним и тем же клиентом за последние два месяца. Нужно понять, **как менялась позиция клиента от встречи к встрече** и какие обещания остались невыполненными. Инструкции по шагам нет — решите сами, что здесь поменять: настройку агента, состав источников в блокноте или сам вопрос к нему.

