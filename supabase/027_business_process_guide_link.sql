Промпт превращает ваши вводные в готовый регламент — но качество результата определяется тем, что вы в него вписали. Какой процесс описывать первым, где у него границы, кто им владеет, как выяснить, что реально происходит вместо того, что написано в инструкциях, где процесс теряет дни и какую цель ставить — это работа, которая делается **до** того, как вы открываете чат.

📎 **[Построение бизнес-процессов в компании](/lesson-files/Построение_бизнес_процессов_в_компании.docx)** — методическое пособие к этому промпту.

Что внутри:
- **Основа:** что такое бизнес-процесс и что им не является (должностная инструкция и оргструктура — не процессы), карта процессов компании в трёх слоях, роль владельца процесса.
- **Восемь шагов:** от выбора первого процесса и определения границ до описания «как есть», поиска потерь, проектирования «как должно быть», матрицы RACI, метрик и написания регламента.
- **Внедрение:** пилот, обучение, контроль первых недель, актуализация и таблица «что делать, если регламент не работает».
- **Десять типичных ошибок** — включая ту, из-за которой процесс проигрывает системе мотивации.
- **Приложения:** чек-лист готовности регламента, вопросы для интервью с исполнителями, карточка процесса на одну страницу, словарь терминов.

